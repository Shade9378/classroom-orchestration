import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('teacher confirmations cover open popups or closed counters, survive tab changes, and work inside dialogs', async ({ page }) => {
  test.setTimeout(60000)
  const tag = randomUUID()
  const post = async (path: string, data: unknown) => {
    const response = await page.request.post(path, { data })
    expect(response.ok(), await response.text()).toBe(true)
    return response.json()
  }
  await post('/api/teacher/register', { name: 'Feedback teacher ' + tag, password: 'Teacher test password' })
  const { session } = await post('/api/sessions', { name: 'Feedback class ' + tag })
  const path = '/api/sessions/' + session.id
  const group = await post(path + '/groups', { name: 'Group 1' })
  const pupil = await post('/api/participants/join', { joinCode: session.joinCode, name: 'Feedback student ' + tag })
  await post(path + '/memberships', { groupId: group.id, participantIds: [pupil.participantId] })
  await post(path + '/device-connections/connect', { sourceId: randomUUID(), name: 'Low phone', type: 'Phone', capabilities: ['Phone'], mode: 'bluetooth', profile: 'custom', model: 'Phone', manufacturer: 'Test', battery: 20 })
  const robot = await post(path + '/devices', { name: 'Offline robot', type: 'Robot', capabilities: ['Robot'], status: 'OFFLINE' })
  await post(path + '/device-assignments', { groupId: group.id, deviceIds: [robot.id] })
  await page.route('**/student-editor.html*', route => route.fulfill({ contentType: 'text/html', body: '<html></html>' }))
  await page.clock.install()
  await page.goto('/?view=groups&session=' + session.id)
  const popups = page.getByRole('complementary', { name: 'Classroom notifications' })
  await expect(popups.locator('.classroom-notification.error')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Select Feedback student ' + tag, exact: true }).check()
  await page.locator('.student-membership-actions').getByRole('button', { name: 'Unassign', exact: true }).click()
  const feedback = page.locator('.teacher-action-feedback')
  await expect(feedback).toContainText('1 student unassigned.')
  expect(await page.locator('.toast').count()).toBe(0)
  const front = await feedback.boundingBox()
  const feed = await popups.locator('.notification-feed').boundingBox()
  expect(Math.abs(front!.y - feed!.y)).toBeLessThan(2)
  expect(await feedback.evaluate(element => Number(getComputedStyle(element).zIndex))).toBeGreaterThan(await popups.evaluate(element => Number(getComputedStyle(element).zIndex)))
  expect(await page.evaluate(({ x, y }) => !!document.elementFromPoint(x, y)?.closest('.teacher-action-feedback'), { x: front!.x + 30, y: front!.y + 15 })).toBe(true)
  await page.screenshot({ path: '.local/action-feedback-expanded.png' })
  await feedback.getByRole('button', { name: 'Dismiss confirmation: 1 student unassigned.', exact: true }).click()
  for (const category of ['Errors (1)', 'Warnings (1)']) {
    const button = popups.getByRole('button', { name: category, exact: true })
    if (await button.getAttribute('aria-pressed') !== 'true') await button.click()
    await button.click()
  }
  await page.locator('.student-group-column').getByRole('button', { name: 'New Group', exact: true }).click()
  await expect(feedback).toContainText('Group 2 created.')
  expect(Math.abs((await feedback.boundingBox())!.y - (await popups.locator('.notification-counts').boundingBox())!.y)).toBeLessThan(2)
  await page.screenshot({ path: '.local/action-feedback-collapsed.png' })
  await page.setViewportSize({ width: 390, height: 700 })
  const mobile = await feedback.boundingBox()
  expect(mobile!.x).toBeGreaterThanOrEqual(0)
  expect(mobile!.x + mobile!.width).toBeLessThanOrEqual(390)
  expect(mobile!.y + mobile!.height).toBeLessThanOrEqual(700)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Activities & Playlists', exact: true }).click()
  await expect(feedback).toContainText('Group 2 created.')
  await feedback.getByRole('button', { name: /Dismiss confirmation/ }).click()
  await page.goto('/?view=live&overviewTab=devices&session=' + session.id)
  await page.locator('.device-overview-table').getByRole('button', { name: 'View Offline robot details', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(dialog.locator('.teacher-action-feedback')).toContainText('Offline robot (Robot) removed from classroom.')
  await dialog.getByRole('button', { name: 'Close device window', exact: true }).click()
  await expect(feedback).toContainText('Offline robot (Robot) removed from classroom.')
  expect(await feedback.evaluate(element => element.parentElement === document.body)).toBe(true)
  await page.clock.fastForward(4100)
  await expect(feedback).toHaveCount(0)
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Group Assignments', exact: true }).click()
  const workGroups=page.locator('.work-assignment-column')
  await expect(workGroups.getByRole('button',{name:'Remove Group',exact:true})).toBeDisabled()
  await workGroups.getByRole('button',{name:'New Group',exact:true}).click()
  const created=workGroups.locator('.group-choice').filter({hasText:'Group 3'})
  await expect(created.getByRole('checkbox')).toBeChecked()
  await workGroups.locator('.group-choice').filter({hasText:'Group 2'}).getByRole('checkbox').check()
  await workGroups.getByRole('button',{name:'Remove Groups',exact:true}).click()
  await expect(workGroups.locator('.group-choice').filter({hasText:'Group 2'})).toHaveCount(0)
  await expect(created).toHaveCount(0)
  await expect(page.locator('.student-group-column .group-choice').filter({hasText:'Group 3'})).toHaveCount(0)
  await page.clock.fastForward(8100)
  await expect(feedback).toHaveCount(0)
  await page.route('**' + path + '/groups', route => route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ message: 'Cannot create this group.' }) }))
  await page.locator('.student-group-column').getByRole('button', { name: 'New Group', exact: true }).click()
  await expect(page.locator('.api-error')).toContainText('Cannot create this group.')
  await expect(feedback).toHaveCount(0)
})

import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
test('Ctrl+S saves and Ctrl+Z undoes activity and playlist edits without crossing items',async({page})=>{
 const request=page.request
 await request.post('/api/teacher/register',{data:{name:`Shortcut teacher ${randomUUID()}`,password:'Shortcut test password'}})
 const a={id:randomUUID(),name:`Shortcut activity ${randomUUID()}`,description:'Original text',starterProject:'',requirements:[{id:randomUUID(),capability:'Robot (RoboScape)',quantity:1}],recoveryPreference:'auto',completionMethod:'teacher',estimatedMinutes:10}
 const b={...a,id:randomUUID(),name:`Other activity ${randomUUID()}`,requirements:[]}
 for(const item of [a,b])await request.put(`/api/activities/${item.id}`,{data:item})
 const p={id:randomUUID(),name:`Shortcut playlist ${randomUUID()}`,description:'Playlist text',activityIds:[a.id,b.id]}
 await request.put(`/api/playlists/${p.id}`,{data:p})
 await page.goto('/')
 await page.locator('.library-item').filter({hasText:a.name}).click()
 const save=page.getByRole('button',{name:'Save Changes',exact:true}),description=page.locator('textarea')
 await expect(save).toBeDisabled()
 const quantity=page.locator('.requirement-row select').nth(1)
 await quantity.selectOption('3')
 await quantity.press('Control+z')
 await expect(quantity).toHaveValue('1')
 await expect(save).toBeDisabled()
 await description.fill('Saved with shortcut')
 await description.press('Control+s')
 await expect.poll(async()=>{const s=await(await request.get('/api/state')).json();return s.activities.find((item:any)=>item.id===a.id).description}).toBe('Saved with shortcut')
 await expect(page.locator('.classroom-content')).toBeEnabled()
 await expect(save).toBeDisabled()
 await description.press('Control+z')
 await expect(description).toHaveValue(a.description)
 await expect(save).toBeEnabled()
 await description.press('Control+s')
 await expect.poll(async()=>{const s=await(await request.get('/api/state')).json();return s.activities.find((item:any)=>item.id===a.id).description}).toBe(a.description)
 await page.locator('.library-item').filter({hasText:b.name}).click()
 await description.press('Control+z')
 await expect(description).toHaveValue(b.description)
 await expect(save).toBeDisabled()
 const preview=page.locator('.playlist-preview')
 await expect(preview.locator('.preview-row')).toHaveCount(2)
 await expect(preview.locator('[draggable=true]')).toHaveCount(0)
 await expect(preview.locator('.lucide-grip-vertical')).toHaveCount(0)
 await page.getByRole('button',{name:'Playlists',exact:true}).click()
 const savePlaylist=page.getByRole('button',{name:'Save Playlist',exact:true})
 await page.getByRole('button',{name:`Remove ${a.name} from playlist`,exact:true}).click()
 await expect(savePlaylist).toBeEnabled()
 await savePlaylist.press('Control+z')
 await expect(page.locator('.playlist-edit-row')).toHaveCount(2)
 await expect(savePlaylist).toBeDisabled()
 await page.locator('.playlist-edit-row').first().dragTo(page.locator('.playlist-edit-row').last())
 await expect(page.locator('.playlist-edit-row').first()).toContainText(b.name)
 await savePlaylist.press('Control+z')
 await expect(page.locator('.playlist-edit-row').first()).toContainText(a.name)
 await expect(savePlaylist).toBeDisabled()
 await description.fill('Saved playlist shortcut')
 await description.press('Control+s')
 await expect.poll(async()=>{const s=await(await request.get('/api/state')).json();return s.playlists.find((item:any)=>item.id===p.id).description}).toBe('Saved playlist shortcut')
 await expect(savePlaylist).toBeDisabled()
})

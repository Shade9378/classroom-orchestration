import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
test('Auto-Assign uses selected devices and displays shortages',async({page})=>{
 const request=page.request
 await request.post('/api/teacher/register',{data:{name:`Auto teacher ${randomUUID()}`,password:'Device assignment test password'}})
 const {session}=await(await request.post('/api/sessions',{data:{name:`Auto devices ${randomUUID()}`}})).json()
 const path=`/api/sessions/${session.id}`
 const group=await(await request.post(`${path}/groups`,{data:{name:'Group 1'}})).json()
 const activity={id:randomUUID(),name:`Robot exercise ${randomUUID()}`,description:'',starterProject:'',requirements:[{id:randomUUID(),capability:'Robot',quantity:2}],recoveryPreference:'auto',completionMethod:'teacher',estimatedMinutes:10}
 expect((await request.put(`/api/activities/${activity.id}`,{data:activity})).ok()).toBeTruthy()
 const later={...activity,id:randomUUID(),name:`Phone exercise ${randomUUID()}`,requirements:[{id:randomUUID(),capability:'Phone / Tablet',quantity:1}]}
 await request.put(`/api/activities/${later.id}`,{data:later})
 const playlist={id:randomUUID(),name:`Test playlist ${randomUUID()}`,description:'',activityIds:[activity.id,later.id]}
 await request.put(`/api/playlists/${playlist.id}`,{data:playlist})
 await request.post(`${path}/assignments`,{data:{groupIds:[group.id],kind:'playlist',id:playlist.id}})
 await request.post(`${path}/devices`,{data:{name:'Offline Phone',type:'Phone',capabilities:['Phone'],status:'OFFLINE'}})
 const selected=await(await request.post(`${path}/devices`,{data:{name:'Selected Robot',type:'Robot',capabilities:['Robot'],status:'OFFLINE'}})).json()
 const unselected=await(await request.post(`${path}/devices`,{data:{name:'Other Robot',type:'Robot',capabilities:['Robot'],status:'ONLINE'}})).json()
 await page.goto(`/?session=${session.id}`)
 await page.getByRole('button',{name:'Group Assignments',exact:true}).click()
 await page.getByRole('button',{name:'Resource Allocation',exact:true}).click()
 const auto=page.getByRole('button',{name:'Auto-Assign',exact:true})
 await expect(auto).toBeDisabled()
 await page.getByRole('checkbox',{name:'Select Selected Robot',exact:true}).check()
 await auto.click()
 await expect(page.locator('.selected-device-summary[role=status]')).toContainText('1 device assigned.')
 await expect(page.locator('.selected-device-summary[role=status]')).toContainText('1x Robot')
 const state=await(await request.get(`/api/state?sessionId=${session.id}`)).json()
 expect(state.devices.find((d:any)=>d.id===selected.id).assignedGroupId).toBe(group.id)
 expect(state.devices.find((d:any)=>d.id===selected.id).status).toBe('offline')
 await expect(page.getByText('Existing assignments kept. Offline and unselected devices were skipped.',{exact:true})).toHaveCount(0)
 expect(state.devices.find((d:any)=>d.id===unselected.id).assignedGroupId).toBeUndefined()
 await page.getByRole('checkbox',{name:'Select Other Robot',exact:true}).check()
 await auto.click()
 await expect(page.locator('.selected-device-summary[role=status]')).toContainText('1x Phone / Tablet')
 await page.getByRole('checkbox',{name:'Select Offline Phone',exact:true}).check()
 await auto.click()
 await expect(page.locator('.selected-device-summary[role=status]')).toContainText('All assigned work requirements have assigned devices.')
 const readiness=page.locator('.readiness-card').filter({has:page.getByRole('heading',{name:'Group 1',exact:true})})
 await expect(readiness).toContainText('Assigned - devices unavailable')
 await expect(readiness).toContainText('Selected Robot: Offline')
 await expect(readiness).toContainText('Offline Phone: Offline')
 await expect(readiness).not.toContainText('Missing')
 await request.put(`/api/activities/${activity.id}`,{data:{...activity,requirements:[{...activity.requirements[0],quantity:3}]}})
 await expect(readiness).toContainText('1x Robot')
 await expect(page.locator('.selected-device-summary[role=status]')).toHaveCount(0)
 await request.put(`/api/playlists/${playlist.id}`,{data:{...playlist,activityIds:[later.id]}})
 await expect(readiness).not.toContainText('Missing')
 await page.locator('input[name="resource-target"]').check()
 const details=page.locator('.selected-group-detail')
 await expect(details).toContainText('1x Phone / Tablet')
 await expect(details.locator('.chip-row')).not.toContainText('Robot')
 const additional={...playlist,id:randomUUID(),name:`Additional playlist ${randomUUID()}`,activityIds:[activity.id]}
 await request.put(`/api/playlists/${additional.id}`,{data:additional})
 await request.post(`${path}/assignments`,{data:{groupIds:[group.id],kind:'playlist',id:additional.id}})
 await request.post(`${path}/assignments`,{data:{groupIds:[group.id],kind:'activity',id:later.id}})
 const work=details.locator('.assigned-work-detail-list')
 await expect(work.locator('li')).toHaveCount(3)
 await expect(work).toContainText(playlist.name)
 await expect(work).toContainText(additional.name)
 await expect(work).toContainText(later.name)
 const fullText=work.locator('details').first()
 await fullText.locator('summary').click()
 await expect(fullText).toHaveAttribute('open','')
 await expect(fullText.getByText('Show less',{exact:true})).toBeVisible()
 await fullText.locator('summary').click()
 await expect(fullText).not.toHaveAttribute('open','')
 await page.getByRole('button',{name:'Edit assigned work for Group 1',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Assignment Preview',exact:true})).toBeVisible()
 const previewText=page.locator('.assignment-preview-content details').first()
 await previewText.locator('summary').click()
 await expect(previewText).toHaveAttribute('open','')
 await previewText.locator('summary').click()
 await expect(previewText).not.toHaveAttribute('open','')
 await expect(page.locator('.assignment-layout .group-choice').filter({hasText:'Group 1'}).getByRole('checkbox')).toBeChecked()
 const listItem=page.locator('.assignment-list .assignment-item:not(.selected)').first()
 const listText=listItem.locator('details')
 await listText.locator('summary').click()
 await expect(listText).toHaveAttribute('open','')
 await expect(listItem.getByRole('radio')).not.toBeChecked()
 await listText.locator('summary').click()
 await expect(listText).not.toHaveAttribute('open','')
 await listItem.getByRole('radio').check()
 await expect(page.locator('.assignment-list .assignment-item.selected').getByRole('radio')).toBeChecked()
 await page.getByRole('button',{name:'Single Activities',exact:true}).click()
 const activityText=page.locator('.assignment-list details').first()
 await activityText.locator('summary').click()
 await expect(activityText).toHaveAttribute('open','')
 await page.getByRole('radio',{name:later.name,exact:true}).check()
 const unassign=page.locator('.work-assignment-actions').getByRole('button',{name:'Unassign',exact:true})
 await expect(unassign).toBeEnabled()
 await unassign.click()
 await expect(page.locator('.work-assignment-actions').getByRole('button',{name:'Unassign',exact:true})).toBeDisabled()
 await expect.poll(async()=>{const snapshot=await(await request.get(`/api/state?sessionId=${session.id}`)).json();return snapshot.groups.find((g:any)=>g.id===group.id).assignedActivityIds}).toEqual([])
 await page.getByRole('button',{name:'Playlists',exact:true}).click()
 await page.getByRole('radio',{name:additional.name,exact:true}).check()
 await page.locator('.work-assignment-actions').getByRole('button',{name:'Unassign',exact:true}).click()
 await expect.poll(async()=>{const snapshot=await(await request.get(`/api/state?sessionId=${session.id}`)).json();return snapshot.groups.find((g:any)=>g.id===group.id).assignedPlaylistIds}).toEqual([playlist.id])



})

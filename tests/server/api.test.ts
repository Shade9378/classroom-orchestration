  expect(await db.session.count({ where: { name: { equals: label, mode: 'insensitive' } } })).toBe(1)
  const a = { ...activity(), name: label }, b = { ...activity(), name: `Other ${randomUUID()}` }
  await service.saveActivity(a); await service.saveActivity(b)
  const save = (data: typeof a) => app.inject({ method: 'PUT', url: `/api/activities/${data.id}`, payload: data })
